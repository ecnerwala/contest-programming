def main(inp, is_real):
    inp = inp.strip().split('\n')
    inp = [eval(x) for x in inp]

    def reduce_num(s):
        while True:
            #print("reducing", s)
            def incr(cur, d, add):
                if add is None:
                    return cur
                if isinstance(cur, int):
                    return cur + add
                else:
                    nxt = [cur[0], cur[1]]
                    nxt[d] = incr(nxt[d], d, add)
                    return nxt

            def explode(cur, depth):
                if isinstance(cur, int):
                    return None
                if depth >= 4:
                    assert isinstance(cur[0], int)
                    assert isinstance(cur[1], int)
                    return (cur[0], 0, cur[1])
                resp = explode(cur[0], depth+1)
                if resp is not None:
                    return (resp[0], [resp[1], incr(cur[1], 0, resp[2])], None)
                resp = explode(cur[1], depth+1)
                if resp is not None:
                    return (None, [incr(cur[0], 1, resp[0]), resp[1]], resp[2])
                return None

            exploded = explode(s, 0)
            if exploded is not None:
                s = exploded[1]
                continue

            def split(cur):
                if isinstance(cur, int):
                    if cur >= 10:
                        return [cur//2, (cur+1)//2]
                    else:
                        return None
                resp = split(cur[0])
                if resp is not None:
                    return [resp, cur[1]]
                resp = split(cur[1])
                if resp is not None:
                    return [cur[0], resp]
                return None
            did_split = split(s)
            if did_split is not None:
                s = did_split
                continue
            break
        return s

    print(reduce_num([[[[[4,3],4],4],[7,[[8,4],9]]],[1,1]]))

    def add_num(a, b):
        return reduce_num([a, b])

    def magnitude(a):
        if isinstance(a, int):
            return a
        return 3 * magnitude(a[0]) + 2 * magnitude(a[1])

    cur = reduce(add_num, inp)
    print(cur)
    cprint(magnitude(cur))
    ans = 0
    for i in range(len(inp)):
        for j in range(len(inp)):
            if i == j:
                continue
            ans = max(ans, magnitude(add_num(inp[i], inp[j])))
    cprint(ans)



