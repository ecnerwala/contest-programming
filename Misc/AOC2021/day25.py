def main(inp, is_real):
    inp = inp.strip().split('\n')
    g = [list(x) for x in inp]
    N = len(g)
    M = len(g[0])

    step = 0
    while True:
        step += 1
        # East first
        moved = False
        ng = [r[:] for r in g]
        for i in range(N):
            for j in range(M):
                if g[i][j] == '>' and g[i][(j+1)%M] == '.':
                    ng[i][j] = '.'
                    ng[i][(j+1)%M] = '>'
                    moved = True
        g = ng
        ng = [r[:] for r in g]
        for i in range(N):
            for j in range(M):
                if g[i][j] == 'v' and g[(i+1)%N][j] == '.':
                    ng[i][j] = '.'
                    ng[(i+1)%N][j] = 'v'
                    moved = True
        g = ng
        if not moved:
            break
    cprint(step)



