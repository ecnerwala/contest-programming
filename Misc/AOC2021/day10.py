def main(inp, is_real):
    inp = inp.strip().split('\n')

    ans = 0
    vals = []
    for l in inp:
        is_good = True
        q = []
        for c in l:
            if c in '<([{':
                q.append(c)
            elif not q or q[-1] != {'}': '{', ')': '(', '>': '<', ']': '['}[c]:
                is_good = False
                break
            else:
                q.pop()
        if not is_good:
            ans += {')': 3, ']': 57, '}': 1197, '>': 25137}[c]
            continue
        score = 0
        for c in q[::-1]:
            score *= 5
            score += {'(': 1, '[': 2, '{': 3, '<': 4}[c]
        vals.append(score)

    vals.sort()

    cprint(ans)
    cprint(vals[len(vals)//2])



