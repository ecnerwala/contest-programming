SEA = [
    '                  # ',
    '#    ##    ##    ###',
    ' #  #  #  #  #  #   ',
]

def cprint(a):
    print(a)
    pyperclip.copy(a)


def main(inp, is_real):
    inp = inp.strip()
    inp = inp.split('\n\n')
    grids = []
    for l in inp:
        title, *grid = l.split('\n')
        grids.append((int(title[5:-1]), list(map(list, grid))))

    grid_map = { idx: g for idx, g in grids }

    patterns = defaultdict(list)

    def get_borders(g):
        top = tuple(g[0])
        bot = tuple(g[-1])
        left = tuple([a[0] for a in g])
        right = tuple([a[-1] for a in g])
        return top, bot, left, right

    for idx, g in grids:
        for b in get_borders(g):
            assert b != b[::-1]
            patterns[b].append(idx)
            patterns[b[::-1]].append(idx)

    def get_reflections(g):
        # There are 8 possibilities
        def a(g):
            yield g
            yield g[::-1]
        def b(g):
            yield from a(g)
            yield from a([x[::-1] for x in g])
        yield from b(g)
        yield from b(list(map(list, zip(*g))))

    def print_grid(g):
        print('\n'.join(''.join(r) for r in g))
        print()

    # Must be oriented and already the left
    def build_row(st):
        _, _, left, right = get_borders(st)
        assert len(patterns[left]) == 1

        res = [a[1:-1] for a in st]

        cur_idx = patterns[left][0]
        while len(patterns[right]) == 2:
            nxt_idx = sum(patterns[right]) - cur_idx
            for cnd in get_reflections(grid_map[nxt_idx]):
                _, _, left, _ = get_borders(cnd)
                if left == right:
                    break
            else: assert False

            _, _, _, right = get_borders(cnd)
            cur_idx = nxt_idx

            res = [a + b[1:-1] for a, b in zip(res, cnd)]

        assert len(patterns[right]) == 1
        return res[1:-1]

    def build_whole(st):
        top, bot, _, _ = get_borders(st)

        res = []
        res += build_row(st)

        assert len(patterns[top]) == 1
        cur_idx = patterns[top][0]
        while len(patterns[bot]) == 2:
            assert cur_idx in patterns[bot]
            nxt_idx = sum(patterns[bot]) - cur_idx
            for cnd in get_reflections(grid_map[nxt_idx]):
                top, _, _, _ = get_borders(cnd)
                if top == bot: break
            else: assert False
            print(top, bot)

            _, bot, _, _ = get_borders(cnd)
            res += build_row(cnd)

            cur_idx = nxt_idx

        assert len(patterns[bot]) == 1
        return res

    for idx, g in grids:
        num_edges = sum(len(patterns[b]) > 1 for b in get_borders(g))
        if num_edges <= 2: break
    else: assert False

    for gr in get_reflections(g):
        top, bot, left, right = get_borders(gr)
        if len(patterns[top]) == 1 and len(patterns[left]) == 1: break
    else: assert False

    whole_grid = build_whole(gr)
    print_grid(whole_grid)

    for g in get_reflections(whole_grid):
        is_sea = set()
        found = False
        for i in range(len(g)-len(SEA)+1):
            for j in range(len(g[i]) - len(SEA[0])+1):
                if all(a==b or b == ' ' for k in range(len(SEA)) for a,b in zip(g[i+k][j:], SEA[k])):
                    for k in range(len(SEA)):
                        for l,(a,b) in enumerate(zip(g[i+k][j:], SEA[k])):
                            if b == ' ': continue
                            assert a == b == '#'
                            is_sea.add((i+k, j+l))
                    found = True
        if found: break
    else: assert False

    ans = 0
    for i, r in enumerate(g):
        for j, c in enumerate(r):
            if c == '#':
                ans += ((i,j)  not in is_sea)
            else:
                assert (i,j) not in is_sea

    cprint(ans)
    #exit(0)


