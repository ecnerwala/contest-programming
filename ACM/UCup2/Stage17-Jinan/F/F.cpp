template <typename T> T mod_inv_in_range(T a, T m) {
	// assert(0 <= a && a < m);
	T x = a, y = m;
	// coeff of a in x and y
	T vx = 1, vy = 0;
	while (x) {
		T k = y / x;
		y %= x;
		vy -= k * vx;
		std::swap(x, y);
		std::swap(vx, vy);
	}
	assert(y == 1);
	return vy < 0 ? m + vy : vy;
}

template <typename T> struct extended_gcd_result {
	T gcd;
	T coeff_a, coeff_b;
};
template <typename T> extended_gcd_result<T> extended_gcd(T a, T b) {
	T x = a, y = b;
	// coeff of a and b in x and y
	T ax = 1, ay = 0;
	T bx = 0, by = 1;
	while (x) {
		T k = y / x;
		y %= x;
		ay -= k * ax;
		by -= k * bx;
		std::swap(x, y);
		std::swap(ax, ay);
		std::swap(bx, by);
	}
	return {y, ay, by};
}

template <typename T> T mod_inv(T a, T m) {
	a %= m;
	a = a < 0 ? a + m : a;
	return mod_inv_in_range(a, m);
}

template <int MOD_> struct modnum {
	static constexpr int MOD = MOD_;
	static_assert(MOD_ > 0, "MOD must be positive");

private:
	int v;

public:

	modnum() : v(0) {}
	modnum(int64_t v_) : v(int(v_ % MOD)) { if (v < 0) v += MOD; }
	explicit operator int() const { return v; }
	friend std::ostream& operator << (std::ostream& out, const modnum& n) { return out << int(n); }
	friend std::istream& operator >> (std::istream& in, modnum& n) { int64_t v_; in >> v_; n = modnum(v_); return in; }

	friend bool operator == (const modnum& a, const modnum& b) { return a.v == b.v; }
	friend bool operator != (const modnum& a, const modnum& b) { return a.v != b.v; }

	modnum inv() const {
		modnum res;
		res.v = mod_inv_in_range(v, MOD);
		return res;
	}
	friend modnum inv(const modnum& m) { return m.inv(); }
	modnum neg() const {
		modnum res;
		res.v = v ? MOD-v : 0;
		return res;
	}
	friend modnum neg(const modnum& m) { return m.neg(); }

	modnum operator- () const {
		return neg();
	}
	modnum operator+ () const {
		return modnum(*this);
	}

	modnum& operator ++ () {
		v ++;
		if (v == MOD) v = 0;
		return *this;
	}
	modnum& operator -- () {
		if (v == 0) v = MOD;
		v --;
		return *this;
	}
	modnum& operator += (const modnum& o) {
		v -= MOD-o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator -= (const modnum& o) {
		v -= o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator *= (const modnum& o) {
		v = int(int64_t(v) * int64_t(o.v) % MOD);
		return *this;
	}
	modnum& operator /= (const modnum& o) {
		return *this *= o.inv();
	}

	friend modnum operator ++ (modnum& a, int) { modnum r = a; ++a; return r; }
	friend modnum operator -- (modnum& a, int) { modnum r = a; --a; return r; }
	friend modnum operator + (const modnum& a, const modnum& b) { return modnum(a) += b; }
	friend modnum operator - (const modnum& a, const modnum& b) { return modnum(a) -= b; }
	friend modnum operator * (const modnum& a, const modnum& b) { return modnum(a) *= b; }
	friend modnum operator / (const modnum& a, const modnum& b) { return modnum(a) /= b; }
};

template <typename T> T pow(T a, long long b) {
	assert(b >= 0);
	T r = 1; while (b) { if (b & 1) r *= a; b >>= 1; a *= a; } return r;
}

using num = modnum<998244353>;
std::vector<num> f_pref_slow(const std::vector<int>& A) {
	int N = int(A.size());
	std::vector<num> res(N+1);
	res[0] = 1;
	for (int i = 1; i <= N; i++) {
		int v = 0;
		for (int j = i-1; j >= 0; j--) {
			v = std::max(v, A[j]);
			if (i-j >= v) res[i] += res[j];
		}
	}
	for (int i = 0; i <= N; i++) { std::cerr << res[i] << ' '; } std::cerr << '\n';
	return res;
}

std::vector<num> f_pref(const std::vector<int>& A) {
	int N = int(A.size());
	std::vector<num> res(N+1);
	seg_tree::in_order_layout layout(N);
	res[0] = 1;

	std::vector<int> num_cover(N);
	std::vector<std::vector<int>> evts(N+1);

	std::y_combinator([&](auto self, seg_tree::point a) -> void {
		if (a >= layout.N) {
			int i = layout.get_leaf_index(a);
			if (A[i] <= 1) {
				cerr << "adding " << res[i] << ' ' << i+1 << '\n';
				res[i+1] += res[i];
			}
			return;
		} else {
			self(a.c(0));
			{
				auto [l, r] = layout.get_node_bounds(a);
				int m = layout.get_node_split(a);
				std::cerr << "process " << l << '-' << m << '-' << r << '\n';
				int v = 0;
				num cur_tot = 0;
				for (int i = m-1; i >= l; i--) {
					v = std::max(v, A[i]);
					int min_r = std::min(std::max(i + l, m), r);
					evts[min_r].push_back(i);
					num_cover[i] = 1;
					cur_tot += res[i];
				}
				int max_l = m;
				v = 0;
				for (int i = m; i < r; i++) {
					std::cerr << "checking " << i << '\n';
					for (int j : evts[i]) {
						assert(num_cover[j] > 0);
						num_cover[j]--;
						if (num_cover[j] == 0) cur_tot += res[j];
						std::cerr << "decr " << j << ' ' << num_cover[j] << ' ' << cur_tot << '\n';
					}
					v = std::max(v, A[i]);
					int nxt_max_l = std::min(std::max(i+1-v, l), m);
					while (max_l > nxt_max_l) {
						max_l--;
						if (num_cover[max_l] == 0) cur_tot -= res[max_l];
						num_cover[max_l]++;
						std::cerr << "incr " << max_l << ' ' << num_cover[max_l] << ' ' << cur_tot << '\n';
					}
					while (max_l < nxt_max_l) {
						assert(num_cover[max_l] > 0);
						num_cover[max_l]--;
						if (num_cover[max_l] == 0) cur_tot += res[max_l];
						std::cerr << "decr " << max_l << ' ' << num_cover[max_l] << ' ' << cur_tot << '\n';
						max_l++;
					}
					std::cerr << "adding " << cur_tot << ' ' << i+1 << '\n';
					res[i+1] += cur_tot;
				}

				// clear out the memory
				for (int i = m; i <= r; i++) evts[i] = {};
			}
			self(a.c(1));
		}
	})(seg_tree::point(1));
	for (int i = 0; i <= N; i++) { std::cerr << res[i] << ' '; } std::cerr << '\n';
	assert(res == f_pref_slow(A));
	return res;
}

std::vector<num> solve(std::vector<int> A) {
	int N = int(A.size());
	std::vector<num> pref_ways = f_pref(A);
	std::reverse(A.begin(), A.end());
	std::vector<num> suff_ways = f_pref(A);
	std::reverse(A.begin(), A.end());
	std::reverse(suff_ways.begin(), suff_ways.end());

	seg_tree::in_order_layout layout(N);
	std::vector<num> res(N, pref_ways[N]);
	for (seg_tree::point a(1); a < layout.N * 2; a++) {
		if (a >= layout.N) {
			int i = layout.get_leaf_index(a);
			if (A[i] > 1) {
				res[i] += pref_ways[i] * suff_ways[i+1];
			}
		} else {
		}
	}

	return res;
}

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int N; cin >> N;
	std::vector<int> A(N);
	for (auto& a : A) cin >> a;

	auto res = solve(A);
	for (int i = 0; i < N; i++) {
		cout << res[i] << " \n"[i+1==N];
	}
	return 0;
}
