#include <cstdio>
#include <bits/stdc++.h>
typedef unsigned long long ull;
struct op {
	std::bitset<128> v[64];
	op() {
		for (int i = 0; i < 64; i++) {
			v[i].reset();
			v[i][i] = true;
		}
	}
	op(const op& a, const op& b) {
		for (int i = 0; i < 64; i++) {
			v[i].reset();
			for (int j = 0; j < 64; j++) {
				if (a.v[i][j]) {
					v[i] ^= b.v[j];
				}
			}
			for (int j = 64; j < 128; j++) {
				if (a.v[i][j]) {
					v[i].flip(j);
				}
			}
		}
	}
	ull operator () (ull x) {
		ull ans = 0;
		for (int i = 0; i < 64; i++) {
			if (x & (1ull << i)) {
				for (int j = 0; j < 64; j++) {
					if (v[i][64+j]) {
						ans ^= (1ull << j);
					}
				}
			}
		}
		return ans;
	}
};

ull ran(){
	static ull x=233;
	x^=x<<13;
	x^=x>>7;
	x^=x<<17;
	return x;
}
op build_ran() {
	op op1;
	for (int i = 0; i+13 < 64; i++) {
		op1.v[i][i+13] = true;
	}
	op op2;
	for (int i = 7; i < 64; i++) {
		op2.v[i][i-7] = true;
	}
	op op3;
	for (int i = 0; i+17 < 64; i++) {
		op3.v[i][i+17] = true;
	}
	return op{op{op1, op2}, op3};
}
op xor_a() {
	op res;
	for (int i = 0; i < 64; i++) {
		res.v[i][64+i] = true;
	}
	return res;
}

