using num = modnum<int(1e9)+7>;

struct range_t {
	num s = 0, a2 = 0, a = 0, l = 1;
	range_t& operator += (range_t o) {
		s += o.s;
		a2 += o.a2;
		a += o.a;
		l += o.l;
		return *this;
	}
	friend range_t operator + (range_t a, range_t b) {
		return range_t(a) += b;
	}
};

struct op_t {
	num a_l = 0;
	num a2_l = 0, a2_a = 0;
	num s_l = 0, s_a = 0, s_a2 = 0;
	op_t() {}
	explicit op_t(num k) : a_l(k), a2_l(k*k), a2_a(2*k) {}
	void apply(range_t& r) {
		r.s += s_l * r.l + s_a * r.a + s_a2 * r.a2;
		r.a2 += a2_l * r.l + a2_a * r.a;
		r.a += a_l * r.l;
	}
	void apply(op_t& o) {
		o.s_l += s_l + s_a * o.a_l + s_a2 * o.a2_l;
		o.s_a += s_a + s_a2 * o.a2_a;
		o.s_a2 += s_a2;

		o.a2_l += a2_l + a2_a * o.a_l;
		o.a2_a += a2_a;

		o.a_l += a_l;
	}
};

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int N, M, Q; cin >> N >> M >> Q;

	std::vector<num> A(N);
	for (auto& a : A) cin >> a;

	std::vector<std::pair<std::array<int, 2>, num>> updates(M);
	for (auto& [b, v] : updates) {
		cin >> b[0] >> b[1]; b[0]--;
		cin >> v;
	}

	std::vector<num> ans(2*Q);
	std::vector<std::vector<std::pair<std::array<int, 2>, int>>> queries(M+1);
	for (int q = 0; q < Q; q++) {
		std::array<int, 2> b; cin >> b[0] >> b[1]; b[0]--;
		int x, y; cin >> x >> y;
		//cerr << x << ' ' << y << '\n';
		x--;
		if (x >= 0) {
			queries[x].push_back({b, 2*q+0});
		} else {
			ans[2*q+0] = 0;
		}
		queries[y].push_back({b, 2*q+1});
	}

	seg_tree::in_order_layout layout(N);
	std::vector<range_t> seg(2*N);
	std::vector<op_t> lazy(2*N);

	auto apply_op = [&](seg_tree::point a, op_t o) -> void {
		o.apply(seg[a]);
		o.apply(lazy[a]);
	};
	auto update_node = [&](seg_tree::point a) -> void {
		assert(a < N);
		seg[a] = seg[a.c(0)] + seg[a.c(1)];
	};
	auto downdate_node = [&](seg_tree::point a) -> void {
		assert(a < N);
		apply_op(a.c(0), lazy[a]);
		apply_op(a.c(1), lazy[a]);
		lazy[a] = op_t();
	};

	for (int i = 0; i < N; i++) {
		auto a = layout.get_point(i);
		seg[a].a2 = A[i] * A[i];
		seg[a].a = A[i];
	}
	for (seg_tree::point a(N-1); a > 0; a--) {
		update_node(a);
	}

	for (int j = 0; j <= M; j++) {
		if (j > 0) {
			auto [b, v] = updates[j-1];
			auto rng = layout.get_range(b);
			rng.for_parents_down(downdate_node);
			op_t o(v);
			rng.for_each([&](auto a, bool) -> void {
				apply_op(a, o);
			});
			rng.for_parents_up(update_node);
		}

		op_t bump;
		bump.s_a2 = 1;
		apply_op(seg_tree::point(1), bump);

		for (auto [b, q] : queries[j]) {
			num res = 0;
			auto rng = layout.get_range(b);
			rng.for_parents_down(downdate_node);
			rng.for_each([&](auto a, bool) -> void {
				res += seg[a].s;
			});
			ans[q] = res;
		}
	}

	for (int q = 0; q < Q; q++) {
		cout << ans[2*q+1] - ans[2*q] << '\n';
	}

	return 0;
}
