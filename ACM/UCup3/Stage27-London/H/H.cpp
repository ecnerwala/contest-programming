using mnum = modnum<998244353>;
using hsh = pairnum<mnum, mnum>;

struct splitmix64_hash {
	static uint64_t splitmix64(uint64_t x) {
		// http://xorshift.di.unimi.it/splitmix64.c
		x += 0x9e3779b97f4a7c15;
		x = (x ^ (x >> 30)) * 0xbf58476d1ce4e5b9;
		x = (x ^ (x >> 27)) * 0x94d049bb133111eb;
		return x ^ (x >> 31);
	}

	size_t operator()(uint64_t x) const {
		static const uint64_t FIXED_RANDOM = std::chrono::steady_clock::now().time_since_epoch().count();
		return splitmix64(x + FIXED_RANDOM);
	}
	size_t operator()(hsh h) const {
		return operator()(uint64_t(int(h.v)) << 32 | uint64_t(int(h.u)));
	}
};

template <typename K, typename V, typename Hash = splitmix64_hash>
using hash_map = __gnu_pbds::gp_hash_table<K, V, Hash>;

template <typename K, typename Hash = splitmix64_hash>
using hash_set = hash_map<K, __gnu_pbds::null_type, Hash>;


int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int N, M, Q; cin >> N >> M >> Q;
	std::vector<std::array<int, 2>> swaps(M);
	for (auto& [u, v] : swaps) { cin >> u >> v; u--, v--; }

	std::vector<std::vector<int>> queries(Q);
	for (auto& b : queries) {
		int k; cin >> k; b.resize(k);
		for (auto& v : b) { cin >> v; v--; }
	}

	const hsh BASE(19283759, 128259837);
	std::vector<hsh> pow_BASE(N+1);
	pow_BASE[0] = 1;
	for (int i = 0; i < N; i++) {
		pow_BASE[i+1] = pow_BASE[i] * BASE;
	}

	std::vector<hsh> tot_hsh(Q);

	const int BLOCK = 20;
	std::vector<hash_map<hsh, std::vector<int>>> small_queries(BLOCK);
	hash_map<hsh, std::vector<std::pair<int, int>>> query_blocks;
	for (int q = 0; q < Q; q++) {
		{
			hsh res = 0;
			for (int z = 0; z < int(queries[q].size()); z++) {
				res += pow_BASE[z] * queries[q][z];
			}
			tot_hsh[q] = res;
		}
		if (int(queries[q].size()) < BLOCK) {
			small_queries[int(queries[q].size())][tot_hsh[q]].push_back(q);
		} else {
			for (int st = 0; st < int(queries[q].size()); st += BLOCK) {
				st = std::min(st, int(queries[q].size()) - BLOCK);
				hsh res = 0;
				for (int z = 0; z < BLOCK; z++) {
					res += pow_BASE[z] * queries[q][st+z];
				}
				query_blocks[res].push_back({q, st});
			}
		}
	}

	seg_tree::in_order_layout layout(N);
	std::vector<hsh> seg(2*N);
	auto update_node = [&](seg_tree::point a) -> void {
		seg[a] = seg[a.c(0)] + seg[a.c(1)] * pow_BASE[layout.get_node_size(a.c(0))];
	};
	auto query_range = [&](int l, int r) -> hsh {
		hsh res = 0;
		layout.get_range(l, r).for_each_r_to_l([&](seg_tree::point a) -> void {
			res *= pow_BASE[layout.get_node_size(a)];
			res += seg[a];
		});
		return res;
	};
	std::vector<int> A(N);
	for (int i = 0; i < N; i++) {
		A[i] = i;
		seg[layout.get_point(i)] = hsh(A[i]);
	}
	for (seg_tree::point a(N-1); a > 0; a--) update_node(a);

	std::vector<int> ans(Q, -1);
	auto check = [&](int i, int l, hsh cur, int t) -> void {
		if (l < BLOCK) {
			auto it = small_queries[l].find(cur);
			if (it != small_queries[l].end()) {
				for (auto q : it->second) {
					ans[q] = t;
				}
				small_queries[l].erase(cur);
			}
		} else {
			auto it = query_blocks.find(cur);
			if (it != query_blocks.end()) {
				for (auto [q, off] : it->second) {
					int st = i - off;
					if (ans[q] == -1 && st >= 0 && st + int(queries[q].size()) <= N && tot_hsh[q] == query_range(st, st + int(queries[q].size()))) {
						ans[q] = t;
					}
				}
			}
		}
	};
	for (int i = 0; i < N; i++) {
		hsh cur = 0;
		for (int l = 1; l <= BLOCK && i + l <= N; l++) {
			cur += pow_BASE[l-1] * A[i + l - 1];
			check(i, l, cur, 0);
		}
	}
	for (int t = 1; t <= M; t++) {
		{
			auto [u, v] = swaps[t-1];
			std::swap(A[u], A[v]);
			seg[layout.get_point(u)] = A[u];
			layout.get_point(u).for_parents_up(update_node);
			seg[layout.get_point(v)] = A[v];
			layout.get_point(v).for_parents_up(update_node);
		}

		// check all points near the swapped ones
		for (int p : swaps[t-1]) {
			hsh st_hsh = 0;
			for (int st = p; st >= 0 && st > p-BLOCK; st--) {
				if (st < p) {
					st_hsh *= BASE;
					st_hsh += A[st];
				}
				hsh cur = st_hsh;
				for (int l = p - st + 1; l <= BLOCK && st + l <= N; l++) {
					cur += pow_BASE[l] * A[st + l - 1];
					check(st, l, cur, 0);
				}
			}
		}
	}
	for (int q = 0; q < Q; q++) {
		cout << ans[q] << '\n';
	}

	return 0;
}
