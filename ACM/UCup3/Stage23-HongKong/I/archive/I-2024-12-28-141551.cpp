template <typename T> T mod_inv_in_range(T a, T m) {
	// assert(0 <= a && a < m);
	T x = a, y = m;
	// coeff of a in x and y
	T vx = 1, vy = 0;
	while (x) {
		T k = y / x;
		y %= x;
		vy -= k * vx;
		std::swap(x, y);
		std::swap(vx, vy);
	}
	assert(y == 1);
	return vy < 0 ? m + vy : vy;
}

template <typename T> struct extended_gcd_result {
	T gcd;
	T coeff_a, coeff_b;
};
template <typename T> extended_gcd_result<T> extended_gcd(T a, T b) {
	T x = a, y = b;
	// coeff of a and b in x and y
	T ax = 1, ay = 0;
	T bx = 0, by = 1;
	while (x) {
		T k = y / x;
		y %= x;
		ay -= k * ax;
		by -= k * bx;
		std::swap(x, y);
		std::swap(ax, ay);
		std::swap(bx, by);
	}
	return {y, ay, by};
}

template <typename T> T mod_inv(T a, T m) {
	a %= m;
	a = a < 0 ? a + m : a;
	return mod_inv_in_range(a, m);
}

template <int MOD_> struct modnum {
	static constexpr int MOD = MOD_;
	static_assert(MOD_ > 0, "MOD must be positive");

private:
	int v;

public:

	modnum() : v(0) {}
	modnum(int64_t v_) : v(int(v_ % MOD)) { if (v < 0) v += MOD; }
	explicit operator int() const { return v; }
	friend std::ostream& operator << (std::ostream& out, const modnum& n) { return out << int(n); }
	friend std::istream& operator >> (std::istream& in, modnum& n) { int64_t v_; in >> v_; n = modnum(v_); return in; }

	friend bool operator == (const modnum& a, const modnum& b) { return a.v == b.v; }
	friend bool operator != (const modnum& a, const modnum& b) { return a.v != b.v; }

	modnum inv() const {
		modnum res;
		res.v = mod_inv_in_range(v, MOD);
		return res;
	}
	friend modnum inv(const modnum& m) { return m.inv(); }
	modnum neg() const {
		modnum res;
		res.v = v ? MOD-v : 0;
		return res;
	}
	friend modnum neg(const modnum& m) { return m.neg(); }

	modnum operator- () const {
		return neg();
	}
	modnum operator+ () const {
		return modnum(*this);
	}

	modnum& operator ++ () {
		v ++;
		if (v == MOD) v = 0;
		return *this;
	}
	modnum& operator -- () {
		if (v == 0) v = MOD;
		v --;
		return *this;
	}
	modnum& operator += (const modnum& o) {
		v -= MOD-o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator -= (const modnum& o) {
		v -= o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator *= (const modnum& o) {
		v = int(int64_t(v) * int64_t(o.v) % MOD);
		return *this;
	}
	modnum& operator /= (const modnum& o) {
		return *this *= o.inv();
	}

	friend modnum operator ++ (modnum& a, int) { modnum r = a; ++a; return r; }
	friend modnum operator -- (modnum& a, int) { modnum r = a; --a; return r; }
	friend modnum operator + (const modnum& a, const modnum& b) { return modnum(a) += b; }
	friend modnum operator - (const modnum& a, const modnum& b) { return modnum(a) -= b; }
	friend modnum operator * (const modnum& a, const modnum& b) { return modnum(a) *= b; }
	friend modnum operator / (const modnum& a, const modnum& b) { return modnum(a) /= b; }
};

template <typename T> T pow(T a, long long b) {
	assert(b >= 0);
	T r = 1; while (b) { if (b & 1) r *= a; b >>= 1; a *= a; } return r;
}

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	using num = modnum<998244353>;
	int64_t N, M; cin >> N >> M;

	std::map<int64_t, int> pfac_map;
	for (auto p : kactl::factor(N)) {
		pfac_map[p]++;
	}

	std::vector<std::pair<int64_t, int>> pfacs(pfac_map.begin(), pfac_map.end());
	int P = int(pfacs.size());
	std::vector<int> strides(P+1);
	strides[0] = 1;
	for (int i = 0; i < P; i++) {
		strides[i+1] = strides[i] * (pfacs[i].second+1);
	}

	int F = strides.back();
	std::vector<int64_t> factors(F);
	factors[0] = 1;
	for (int i = 0; i < P; i++) {
		for (int v = strides[i]; v < strides[i+1]; v++) {
			factors[v] = factors[v - strides[i]] * pfacs[i].first;
		}
	}

	std::vector<int64_t> ways_single(F);
	for (int f = 0; f < F; f++) {
		ways_single[f] = M / factors[f];
	}
	std::vector<int> mu(F);
	mu[0] = 1;
	for (int i = 0; i < P; i++) {
		for (int v = 0; v < F; v++) {
			if (v % strides[i+1] / strides[i] == 0) continue;
			ways_single[v - strides[i]] -= ways_single[v];
			mu[v - strides[i]] -= mu[v];
		}
	}

	// number of ways of solving a single tree
	std::vector<num> dp(F);
	for (int f = F-1; f >= 0; f--) {
		dp[f] = ways_single[f];
		for (int f2 = f+1; f2 < F; f2++) {
			if (factors[f2] % factors[f]) continue;
			cerr << f2 << ' ' << mu[f2 - f] << ' ' << pow(dp[f2], factors[f2] / factors[f]) << '\n';
			dp[f] -= mu[f2 - f] * pow(dp[f2], factors[f2] / factors[f]);
		}
		cerr << f << ' ' << ways_single[f] << ' ' << factors[f] << ' ' << dp[f] << '\n';
	}

	cout << dp[0] << '\n';

	return 0;
}
