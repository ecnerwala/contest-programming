template <typename T> T mod_inv_in_range(T a, T m) {
	// assert(0 <= a && a < m);
	T x = a, y = m;
	// coeff of a in x and y
	T vx = 1, vy = 0;
	while (x) {
		T k = y / x;
		y %= x;
		vy -= k * vx;
		std::swap(x, y);
		std::swap(vx, vy);
	}
	assert(y == 1);
	return vy < 0 ? m + vy : vy;
}

template <typename T> struct extended_gcd_result {
	T gcd;
	T coeff_a, coeff_b;
};
template <typename T> extended_gcd_result<T> extended_gcd(T a, T b) {
	T x = a, y = b;
	// coeff of a and b in x and y
	T ax = 1, ay = 0;
	T bx = 0, by = 1;
	while (x) {
		T k = y / x;
		y %= x;
		ay -= k * ax;
		by -= k * bx;
		std::swap(x, y);
		std::swap(ax, ay);
		std::swap(bx, by);
	}
	return {y, ay, by};
}

template <typename T> T mod_inv(T a, T m) {
	a %= m;
	a = a < 0 ? a + m : a;
	return mod_inv_in_range(a, m);
}

template <int MOD_> struct modnum {
	static constexpr int MOD = MOD_;
	static_assert(MOD_ > 0, "MOD must be positive");

private:
	int v;

public:

	modnum() : v(0) {}
	modnum(int64_t v_) : v(int(v_ % MOD)) { if (v < 0) v += MOD; }
	explicit operator int() const { return v; }
	friend std::ostream& operator << (std::ostream& out, const modnum& n) { return out << int(n); }
	friend std::istream& operator >> (std::istream& in, modnum& n) { int64_t v_; in >> v_; n = modnum(v_); return in; }

	friend bool operator == (const modnum& a, const modnum& b) { return a.v == b.v; }
	friend bool operator != (const modnum& a, const modnum& b) { return a.v != b.v; }

	modnum inv() const {
		modnum res;
		res.v = mod_inv_in_range(v, MOD);
		return res;
	}
	friend modnum inv(const modnum& m) { return m.inv(); }
	modnum neg() const {
		modnum res;
		res.v = v ? MOD-v : 0;
		return res;
	}
	friend modnum neg(const modnum& m) { return m.neg(); }

	modnum operator- () const {
		return neg();
	}
	modnum operator+ () const {
		return modnum(*this);
	}

	modnum& operator ++ () {
		v ++;
		if (v == MOD) v = 0;
		return *this;
	}
	modnum& operator -- () {
		if (v == 0) v = MOD;
		v --;
		return *this;
	}
	modnum& operator += (const modnum& o) {
		v -= MOD-o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator -= (const modnum& o) {
		v -= o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator *= (const modnum& o) {
		v = int(int64_t(v) * int64_t(o.v) % MOD);
		return *this;
	}
	modnum& operator /= (const modnum& o) {
		return *this *= o.inv();
	}

	friend modnum operator ++ (modnum& a, int) { modnum r = a; ++a; return r; }
	friend modnum operator -- (modnum& a, int) { modnum r = a; --a; return r; }
	friend modnum operator + (const modnum& a, const modnum& b) { return modnum(a) += b; }
	friend modnum operator - (const modnum& a, const modnum& b) { return modnum(a) -= b; }
	friend modnum operator * (const modnum& a, const modnum& b) { return modnum(a) *= b; }
	friend modnum operator / (const modnum& a, const modnum& b) { return modnum(a) /= b; }
};

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int N, M, Q; cin >> N >> M >> Q;
	std::vector<int> A(N+1);
	for (int i = 1; i <= N; i++) {
		cin >> A[i];
	}
	A[0] = 0;

	using num = modnum<998244353>;

	struct seg_t {
		int min_height;
		// we have some number of things at min_height -> min_height + 1
		// by convention, we store dp_l[M, min_height) + dp_r[min_height] + dp_r(min_height, M]
		std::vector<std::vector<num>> dp_l;
		std::vector<std::vector<num>> dp_r;
	};
	seg_t id;
	id.min_height = M;
	id.dp_l.resize(M+1);
	id.dp_r.resize(M+1);
	for (int i = 0; i <= M; i++) {
		// id.dp[i] is fft([1, 0, 0, 0, 0, 0]) => identically num(1)
		id.dp_l[i].assign(i+1, num(1));
		id.dp_r[i].assign(i+1, num(1));
	}

	seg_t single_op = id;
	{
		// set v to fft([0, 1, 0, 0, 0, 0]), i.e. every bitstring of length 1 has weight 1
		auto& v = single_op.dp_r[M];
		for (int a = 0; a <= M; a++) {
			v[a] = num(M - 2 * a);
		}
	}

	seg_tree::in_order_layout layout(2*N+1);
	std::vector<seg_t> seg(2*layout.N);
	auto update_node = [&](seg_tree::point a) -> void {
		// TODO: put things in
		if (a >= layout.N) {
			int idx = layout.get_leaf_index(a);
			if (idx & 1) {
				seg[a] = single_op;
			} else {
				int h = A[idx / 2];
				seg[a] = id;
				seg[a].min_height = h;
			}
		} else {
			auto& s = seg[a];
			const auto& c0 = seg[a.c(0)];
			const auto& c1 = seg[a.c(1)];
			s.min_height = std::min(c0.min_height, c1.min_height);
			int max_h = std::max(c0.min_height, c1.min_height);
			std::vector<num> dp(M+1, num(1));
			for (int i = M; i > max_h; i--) {
				for (int v = 0; v <= i; v++) {
					dp[v] *= c0.dp_r[i][v];
					dp[v] *= c1.dp_l[i][v];
				}
				// now, we should shrink it by 1
				for (int v = 0; v < i; v++) {
					dp[v] += dp[v+1];
					dp[v] /= num(2);
				}
				dp.pop_back();
			}
			assert(int(dp.size()) == max_h + 1);

			if (c0.min_height <= c1.min_height) {
				s = c0;
				assert(c1.min_height == max_h);
				for (int v = 0; v <= max_h; v++) {
					s.dp_r[max_h][v] *= dp[v] * c1.dp_r[max_h][v];
				}
				for (int i = max_h + 1; i <= M; i++) {
					s.dp_r[i] = c1.dp_r[i];
				}
			} else {
				s = c1;
				assert(c0.min_height == max_h);
				for (int v = 0; v <= max_h; v++) {
					s.dp_l[max_h][v] *= c0.dp_r[max_h][v] * dp[v];
				}
				for (int i = c0.min_height + 1; i <= M; i++) {
					s.dp_l[i] = c0.dp_l[i];
				}
			}
		}
	};
	auto get_ans = [&]() -> num {
		const auto& s = seg[1];
		assert(s.min_height == 0);

		num ans = 1;
		for (int i = 0; i <= M; i++) {
			ans *= s.dp_r[i][0];
		}
		return ans;
	};

	for (seg_tree::point a(int(seg.size())-1); a > 0; a--) update_node(a);

	for (int q = 0; q < Q; q++) {
		int x, y; cin >> x >> y;
		A[x] = y;
		auto a = layout.get_point(2 * x);
		// TODO: Could optimize this
		update_node(a);
		a.for_parents_up(update_node);
		cout << get_ans() << '\n';
	}

	return 0;
}
