template <typename T> T mod_inv_in_range(T a, T m) {
	// assert(0 <= a && a < m);
	T x = a, y = m;
	// coeff of a in x and y
	T vx = 1, vy = 0;
	while (x) {
		T k = y / x;
		y %= x;
		vy -= k * vx;
		std::swap(x, y);
		std::swap(vx, vy);
	}
	assert(y == 1);
	return vy < 0 ? m + vy : vy;
}

template <typename T> struct extended_gcd_result {
	T gcd;
	T coeff_a, coeff_b;
};
template <typename T> extended_gcd_result<T> extended_gcd(T a, T b) {
	T x = a, y = b;
	// coeff of a and b in x and y
	T ax = 1, ay = 0;
	T bx = 0, by = 1;
	while (x) {
		T k = y / x;
		y %= x;
		ay -= k * ax;
		by -= k * bx;
		std::swap(x, y);
		std::swap(ax, ay);
		std::swap(bx, by);
	}
	return {y, ay, by};
}

template <typename T> T mod_inv(T a, T m) {
	a %= m;
	a = a < 0 ? a + m : a;
	return mod_inv_in_range(a, m);
}

template <int MOD_> struct modnum {
	static constexpr int MOD = MOD_;
	static_assert(MOD_ > 0, "MOD must be positive");

private:
	int v;

public:

	modnum() : v(0) {}
	modnum(int64_t v_) : v(int(v_ % MOD)) { if (v < 0) v += MOD; }
	explicit operator int() const { return v; }
	friend std::ostream& operator << (std::ostream& out, const modnum& n) { return out << int(n); }
	friend std::istream& operator >> (std::istream& in, modnum& n) { int64_t v_; in >> v_; n = modnum(v_); return in; }

	friend bool operator == (const modnum& a, const modnum& b) { return a.v == b.v; }
	friend bool operator != (const modnum& a, const modnum& b) { return a.v != b.v; }

	modnum inv() const {
		modnum res;
		res.v = mod_inv_in_range(v, MOD);
		return res;
	}
	friend modnum inv(const modnum& m) { return m.inv(); }
	modnum neg() const {
		modnum res;
		res.v = v ? MOD-v : 0;
		return res;
	}
	friend modnum neg(const modnum& m) { return m.neg(); }

	modnum operator- () const {
		return neg();
	}
	modnum operator+ () const {
		return modnum(*this);
	}

	modnum& operator ++ () {
		v ++;
		if (v == MOD) v = 0;
		return *this;
	}
	modnum& operator -- () {
		if (v == 0) v = MOD;
		v --;
		return *this;
	}
	modnum& operator += (const modnum& o) {
		v -= MOD-o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator -= (const modnum& o) {
		v -= o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator *= (const modnum& o) {
		v = int(int64_t(v) * int64_t(o.v) % MOD);
		return *this;
	}
	modnum& operator /= (const modnum& o) {
		return *this *= o.inv();
	}

	friend modnum operator ++ (modnum& a, int) { modnum r = a; ++a; return r; }
	friend modnum operator -- (modnum& a, int) { modnum r = a; --a; return r; }
	friend modnum operator + (const modnum& a, const modnum& b) { return modnum(a) += b; }
	friend modnum operator - (const modnum& a, const modnum& b) { return modnum(a) -= b; }
	friend modnum operator * (const modnum& a, const modnum& b) { return modnum(a) *= b; }
	friend modnum operator / (const modnum& a, const modnum& b) { return modnum(a) /= b; }
};

template <typename T> T pow(T a, long long b) {
	assert(b >= 0);
	T r = 1; while (b) { if (b & 1) r *= a; b >>= 1; a *= a; } return r;
}

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int N; cin >> N;
	std::vector<std::vector<int>> adj(N);
	for (int e = 0; e < N-2; e++) {
		int u, v; cin >> u >> v; u--, v--;
		adj[u].push_back(v);
		adj[v].push_back(u);
	}

	using num = modnum<998244353>;
	std::vector<num> p2(N+1);
	p2[0] = 1;
	for (int i = 1; i <= N; i++) p2[i] = p2[i-1] + p2[i-1];

	std::vector<bool> is_t0(N);
	std::y_combinator([&](auto self, int cur, int prv) -> void {
		is_t0[cur] = true;
		for (int nxt : adj[cur]) {
			if (nxt == prv) continue;
			self(nxt, cur);
		}
	})(0, -1);

	int r1 = 0;
	while (is_t0[r1]) r1++;

	num extra_ans = 0;

	num tot_ans = 1;
	for (int z = 1; z >= 0; z--) {
		std::vector<int> st(N, -1);
		std::vector<int> en(N, -1);
		int num_t1 = 0;
		{
			std::y_combinator([&](auto self, int cur, int prv) -> void {
				st[cur] = num_t1;
				num_t1++;
				for (int nxt : adj[cur]) {
					if (nxt == prv) continue;
					self(nxt, cur);
				}
				en[cur] = num_t1;
			})(z ? r1 : 0, -1);
		}
		num ans_t1 = 0;
		{
			seg_tree::in_order_layout layout(num_t1);
			std::vector<int> seg(num_t1 * 2);
			std::vector<num> seg2(num_t1 * 2, num(1));
			int tot_bigger = 0;
			for (int i = N-1; i >= 0; i--) {
				if (is_t0[i] != !z) continue;
				assert(st[i] != -1);
				assert(en[i] != -1);
				for (int j : adj[i]) {
					int cnt = tot_bigger;
					auto remove = [&](int l, int r) -> void {
						layout.get_range(l, r).for_each([&](seg_tree::point a) -> void { cnt -= seg[a]; });
					};
					if (st[j] < st[i]) {
						// j is the parent
						remove(0, st[i]);
						remove(en[i], num_t1);
					} else {
						remove(st[j], en[j]);
					}
					num v = p2[cnt];
					auto incr = [&](int l, int r) -> void {
						layout.get_range(l, r).for_each([&](seg_tree::point a) -> void { seg2[a] *= v; });
					};
					if (st[j] < st[i]) {
						incr(0, st[i]);
						incr(en[i], num_t1);
					} else {
						incr(st[j], en[j]);
					}
				}
				seg2[layout.get_point(st[i])] *= p2[tot_bigger];

				layout.get_point(st[i]).for_each([&](seg_tree::point a) -> void { seg[a] ++; });
				tot_bigger++;
			}
			for (int i = 1; i < num_t1; i++) {
				seg2[2*i+0] *= seg2[i];
				seg2[2*i+1] *= seg2[i];
			}
			if (z == 1) {
				for (int i = 0; i < num_t1; i++) {
					ans_t1 += seg2[num_t1 + i];
				}
			} else {
				ans_t1 += seg2[layout.get_point(st[0])];
			}
		}
		cerr << z << ' ' << ans_t1 << '\n';
		tot_ans *= ans_t1;
		if (z == 0) extra_ans = ans_t1;
	}

	{
		num ans_cross = 0;
		std::vector<num> vals(N);
		{
			int cnt = 0;
			for (int i = N-1; i >= 0; i--) {
				if (is_t0[i]) {
					vals[i] = p2[cnt];
				} else {
					cnt++;
				}
			}
		}
		std::y_combinator([&](auto self, int cur, int prv, num v) -> void {
			v *= vals[cur];
			ans_cross += v;
			for (int nxt : adj[cur]) {
				if (nxt == prv) continue;
				self(nxt, cur, v);
			}
		})(0, -1, num(1));
		cerr << ans_cross << '\n';
		tot_ans *= ans_cross;
	}

	// don't count node 0 itself
	tot_ans /= p2[N-1];
	if (adj[r1].empty()) {
		tot_ans += extra_ans / p2[N-2];
	}
	cout << tot_ans << '\n';

	return 0;
}
