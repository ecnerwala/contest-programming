int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int N, Q; cin >> N >> Q;
	string S; cin >> S;

	using mnum = modnum<998244353>;
	using matrix_t = std::array<std::array<mnum, 3>, 3>;
	auto mul = [&](const matrix_t& a, const matrix_t& b) -> matrix_t {
		matrix_t r;
		for (int i = 0; i < 3; i++) {
			for (int j = 0; j < 3; j++) {
				r[i][j] = 0;
				for (int k = 0; k < 3; k++) {
					r[i][j] += a[i][k] * b[k][j];
				}
			}
		}
		return r;
	};

	matrix_t ID;
	for (int i = 0; i < 3; i++) {
		for (int j = 0; j < 3; j++) {
			ID[i][j] = (i == j ? 1 : 0);
		}
	}

	std::mt19937 mt(48);
	std::array<matrix_t, 3> BASES;
	for (int z = 0; z < 3; z++) {
		std::array<mnum, 3> v;
		v[0] = mt();
		v[1] = mt();
		mnum d = mt();
		mnum s = (v[0] * v[0] + v[1] * v[1]) / d;
		v[2] = (s - d) / 2;
		mnum norm = (s + d) / 2;

		v[0] /= norm;
		v[1] /= norm;
		v[2] /= norm;

		BASES[z] = ID;
		for (int i = 0; i < 3; i++) {
			for (int j = 0; j < 3; j++) {
				BASES[z][i][j] -= v[i] * v[j] * 2;
			}
		}
	}

	seg_tree::in_order_layout layout(N);
	struct seg_t {
		std::array<matrix_t, 3> m;
		int lazy_cyc;
	};
	std::vector<seg_t> seg(2*N);
	auto update_node = [&](seg_tree::point a) -> void {
		if (a >= N) {
			seg[a].m = BASES;
		} else {
			for (int i = 0; i < 3; i++) {
				seg[a].m[i] = mul(seg[a.c(0)].m[i], seg[a.c(1)].m[i]);
			}
		}
		std::rotate(seg[a].m.begin(), seg[a].m.begin() + (seg[a].lazy_cyc % 3), seg[a].m.end());
	};
	auto apply_val = [&](seg_tree::point a, int v) -> void {
		seg[a].lazy_cyc += v;
		std::rotate(seg[a].m.begin(), seg[a].m.begin() + (v % 3), seg[a].m.end());
	};
	auto downdate_node = [&](seg_tree::point a) -> void {
		if (a >= N) return;
		if (seg[a].lazy_cyc % 3) {
			apply_val(a.c(0), seg[a].lazy_cyc);
			apply_val(a.c(1), seg[a].lazy_cyc);
		}
		seg[a].lazy_cyc = 0;
	};

	for (int i = 0; i < N; i++) {
		auto a = layout.get_point(i);
		seg[a].lazy_cyc = S[i];
		update_node(a);
	}
	for (seg_tree::point a(N-1); a > 0; a--) {
		update_node(a);
	}

	for (int q = 0; q < Q; q++) {
		int op; cin >> op;
		if (op == 1) {
			int l, r; cin >> l >> r; l--;
			auto rng = layout.get_range(l, r);
			rng.for_each([&](auto a) -> void {
				apply_val(a, 1);
			});
			rng.for_parents_up(update_node);
		} else if (op == 2) {
			int l, r; cin >> l >> r; l--;
			auto rng = layout.get_range(l, r);
			rng.for_parents_down(downdate_node);
			matrix_t cur = ID;
			rng.for_each_l_to_r([&](auto a) -> void {
				cur = mul(cur, seg[a].m[0]);
			});
			cout << (cur == ID ? "Yes" : "No") << '\n';
		} else assert(false);
	}

	return 0;
}
