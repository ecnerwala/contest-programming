int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int T; cin >> T;
	while (T--) {
		int N; cin >> N;
		struct int_t {
			int l, r, c;
		};
		std::vector<int_t> A(N);
		std::vector<int> coords; coords.reserve(2*N);
		for (auto& [l, r, c] : A) {
			cin >> l >> r >> c;
			r++;
			coords.push_back(l);
			coords.push_back(r);
		}
		std::sort(coords.begin(), coords.end());
		coords.resize(std::unique(coords.begin(), coords.end()) - coords.begin());

		for (auto& [l, r, _] : A) {
			l = int(std::lower_bound(coords.begin(), coords.end(), l) - coords.begin());
			r = int(std::lower_bound(coords.begin(), coords.end(), r) - coords.begin());
		}

		std::sort(A.begin(), A.end(), [&](auto x, auto y) { return x.r < y.r; });

		using num = modnum<998244353>;

		struct seg_t {
			num ways = 0;
			num lazy = 1;
		};

		seg_tree::in_order_layout layout(int(coords.size()));
		std::array<std::vector<seg_t>, 2> seg;
		seg[0].resize(2*layout.N);
		seg[1].resize(2*layout.N);

		auto update_node = [&seg](int z) {
			return [&seg,z](seg_tree::point a) {
				seg[z][a].ways = seg[z][a.c(0)].ways + seg[z][a.c(1)].ways;
			};
		};
		auto apply_lazy = [&](int z, seg_tree::point a, num v) {
			seg[z][a].ways *= v;
			seg[z][a].lazy *= v;
		};
		auto downdate_node = [&](int z) {
			return [&,z](seg_tree::point a) {
				if (a < layout.N) {
					apply_lazy(z, a.c(0), seg[z][a].lazy);
					apply_lazy(z, a.c(1), seg[z][a].lazy);
				}
				seg[z][a].lazy = 1;
			};
		};

		{
			auto a = layout.get_point(0);
			for (int z = 0; z < 2; z++) {
				seg[z][a].ways = 1;
				a.for_parents_up(update_node(z));
			}
		}

		num ans = 1;
		for (auto [l, r, c] : A) {
			num v = 0;
			{
				int z = !c;
				auto rng = layout.get_range(0, l+1);
				rng.for_parents_down(downdate_node(z));
				rng.for_each([&](auto a) -> void {
					v += seg[z][a].ways;
					seg[z][a].ways *= 2;
					seg[z][a].lazy *= 2;
				});
				rng.for_parents_up(update_node(z));
			}
			ans += v;
			{
				int z = c;
				auto a = layout.get_point(r);
				a.for_parents_down(downdate_node(z));
				seg[z][a].ways += v;
				a.for_parents_up(update_node(z));
			}
		}
		cout << ans << '\n';
	}

	return 0;
}
