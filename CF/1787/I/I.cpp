#include <bits/stdc++.h>

namespace std {

template<class Fun>
class y_combinator_result {
	Fun fun_;
public:
	template<class T>
	explicit y_combinator_result(T &&fun): fun_(std::forward<T>(fun)) {}

	template<class ...Args>
	decltype(auto) operator()(Args &&...args) {
		return fun_(std::ref(*this), std::forward<Args>(args)...);
	}
};

template<class Fun>
decltype(auto) y_combinator(Fun &&fun) {
	return y_combinator_result<std::decay_t<Fun>>(std::forward<Fun>(fun));
}

} // namespace std

template <typename T> T mod_inv_in_range(T a, T m) {
	// assert(0 <= a && a < m);
	T x = a, y = m;
	T vx = 1, vy = 0;
	while (x) {
		T k = y / x;
		y %= x;
		vy -= k * vx;
		std::swap(x, y);
		std::swap(vx, vy);
	}
	assert(y == 1);
	return vy < 0 ? m + vy : vy;
}

template <typename T> T mod_inv(T a, T m) {
	a %= m;
	a = a < 0 ? a + m : a;
	return mod_inv_in_range(a, m);
}

template <int MOD_> struct modnum {
	static constexpr int MOD = MOD_;
	static_assert(MOD_ > 0, "MOD must be positive");

private:
	int v;

public:

	modnum() : v(0) {}
	modnum(int64_t v_) : v(int(v_ % MOD)) { if (v < 0) v += MOD; }
	explicit operator int() const { return v; }
	friend std::ostream& operator << (std::ostream& out, const modnum& n) { return out << int(n); }
	friend std::istream& operator >> (std::istream& in, modnum& n) { int64_t v_; in >> v_; n = modnum(v_); return in; }

	friend bool operator == (const modnum& a, const modnum& b) { return a.v == b.v; }
	friend bool operator != (const modnum& a, const modnum& b) { return a.v != b.v; }

	modnum inv() const {
		modnum res;
		res.v = mod_inv_in_range(v, MOD);
		return res;
	}
	friend modnum inv(const modnum& m) { return m.inv(); }
	modnum neg() const {
		modnum res;
		res.v = v ? MOD-v : 0;
		return res;
	}
	friend modnum neg(const modnum& m) { return m.neg(); }

	modnum operator- () const {
		return neg();
	}
	modnum operator+ () const {
		return modnum(*this);
	}

	modnum& operator ++ () {
		v ++;
		if (v == MOD) v = 0;
		return *this;
	}
	modnum& operator -- () {
		if (v == 0) v = MOD;
		v --;
		return *this;
	}
	modnum& operator += (const modnum& o) {
		v -= MOD-o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator -= (const modnum& o) {
		v -= o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator *= (const modnum& o) {
		v = int(int64_t(v) * int64_t(o.v) % MOD);
		return *this;
	}
	modnum& operator /= (const modnum& o) {
		return *this *= o.inv();
	}

	friend modnum operator ++ (modnum& a, int) { modnum r = a; ++a; return r; }
	friend modnum operator -- (modnum& a, int) { modnum r = a; --a; return r; }
	friend modnum operator + (const modnum& a, const modnum& b) { return modnum(a) += b; }
	friend modnum operator - (const modnum& a, const modnum& b) { return modnum(a) -= b; }
	friend modnum operator * (const modnum& a, const modnum& b) { return modnum(a) *= b; }
	friend modnum operator / (const modnum& a, const modnum& b) { return modnum(a) /= b; }
};

template <typename T> T pow(T a, long long b) {
	assert(b >= 0);
	T r = 1; while (b) { if (b & 1) r *= a; b >>= 1; a *= a; } return r;
}

namespace seg_tree {

// Floor of log_2(a); index of highest 1-bit
inline int log_2(int a) {
	return a ? (8 * sizeof(a)) - 1 - __builtin_clz(a) : -1;
}

inline int next_pow_2(int a) {
	assert(a > 0);
	return 1 << log_2(2*a-1);
}

struct point {
	int a;
	point() : a(0) {}
	explicit point(int a_) : a(a_) { assert(a >= -1); }

	explicit operator bool () { return bool(a); }

	// This is useful so you can directly do array indices
	/* implicit */ operator int() const { return a; }

	point c(bool z) const {
		return point((a<<1)|z);
	}

	point operator [] (bool z) const {
		return c(z);
	}

	point p() const {
		return point(a>>1);
	}

	friend std::ostream& operator << (std::ostream& o, const point& p) { return o << int(p); }

	template <typename F> void for_each(F f) const {
		for (int v = a; v > 0; v >>= 1) {
			f(point(v));
		}
	}

	template <typename F> void for_parents_down(F f) const {
		// strictly greater than 0
		for (int L = log_2(a); L > 0; L--) {
			f(point(a >> L));
		}
	}

	template <typename F> void for_parents_up(F f) const {
		for (int v = a >> 1; v > 0; v >>= 1) {
			f(point(v));
		}
	}

	point& operator ++ () { ++a; return *this; }
	point operator ++ (int) { return point(a++); }
	point& operator -- () { --a; return *this; }
	point operator -- (int) { return point(a--); }
};

struct range {
	int a, b;
	range() : a(1), b(1) {}
	range(int a_, int b_) : a(a_), b(b_) {
		assert(1 <= a && a <= b && b <= 2 * a);
	}
	explicit range(std::array<int, 2> r) : range(r[0], r[1]) {}

	explicit operator std::array<int, 2>() const {
		return {a,b};
	}

	const int& operator[] (bool z) const {
		return z ? b : a;
	}

	friend std::ostream& operator << (std::ostream& o, const range& r) { return o << "[" << r.a << ".." << r.b << ")"; }

	// Iterate over the range from outside-in.
	//   Calls f(point a)
	template <typename F> void for_each(F f) const {
		for (int x = a, y = b; x < y; x >>= 1, y >>= 1) {
			if (x & 1) f(point(x++));
			if (y & 1) f(point(--y));
		}
	}

	// Iterate over the range from outside-in.
	//   Calls f(point a, bool is_right)
	template <typename F> void for_each_with_side(F f) const {
		for (int x = a, y = b; x < y; x >>= 1, y >>= 1) {
			if (x & 1) f(point(x++), false);
			if (y & 1) f(point(--y), true);
		}
	}

	// Iterate over the range from left to right.
	//    Calls f(point)
	template <typename F> void for_each_l_to_r(F f) const {
		int anc_depth = log_2((a-1) ^ b);
		int anc_msk = (1 << anc_depth) - 1;
		for (int v = (-a) & anc_msk; v; v &= v-1) {
			int i = __builtin_ctz(v);
			f(point(((a-1) >> i) + 1));
		}
		for (int v = b & anc_msk; v; ) {
			int i = log_2(v);
			f(point((b >> i) - 1));
			v ^= (1 << i);
		}
	}

	// Iterate over the range from right to left.
	//    Calls f(point)
	template <typename F> void for_each_r_to_l(F f) const {
		int anc_depth = log_2((a-1) ^ b);
		int anc_msk = (1 << anc_depth) - 1;
		for (int v = b & anc_msk; v; v &= v-1) {
			int i = __builtin_ctz(v);
			f(point((b >> i) - 1));
		}
		for (int v = (-a) & anc_msk; v; ) {
			int i = log_2(v);
			f(point(((a-1) >> i) + 1));
			v ^= (1 << i);
		}
	}

	template <typename F> void for_parents_down(F f) const {
		int x = a, y = b;
		if ((x ^ y) > x) { x <<= 1, std::swap(x, y); }
		int dx = __builtin_ctz(x);
		int dy = __builtin_ctz(y);
		int anc_depth = log_2((x-1) ^ y);
		for (int i = log_2(x); i > dx; i--) {
			f(point(x >> i));
		}
		for (int i = anc_depth; i > dy; i--) {
			f(point(y >> i));
		}
	}

	template <typename F> void for_parents_up(F f) const {
		int x = a, y = b;
		if ((x ^ y) > x) { x <<= 1, std::swap(x, y); }
		int dx = __builtin_ctz(x);
		int dy = __builtin_ctz(y);
		int anc_depth = log_2((x-1) ^ y);
		for (int i = dx+1; i <= anc_depth; i++) {
			f(point(x >> i));
		}
		for (int v = y >> (dy+1); v; v >>= 1) {
			f(point(v));
		}
	}
};

struct in_order_layout {
	// Alias them in for convenience
	using point = seg_tree::point;
	using range = seg_tree::range;

	int N, S;
	in_order_layout() : N(0), S(0) {}
	in_order_layout(int N_) : N(N_), S(N ? next_pow_2(N) : 0) {}

	point get_point(int a) const {
		assert(0 <= a && a < N);
		a += S;
		return point(a >= 2 * N ? a - N : a);
	}

	range get_range(int a, int b) const {
		assert(0 <= a && a <= b && b <= N);
		if (N == 0) return range();
		a += S, b += S;
		return range((a >= 2 * N ? 2*(a-N) : a), (b >= 2 * N ? 2*(b-N) : b));
	}

	range get_range(std::array<int, 2> p) const {
		return get_range(p[0], p[1]);
	}

	int get_leaf_index(point pt) const {
		int a = int(pt);
		assert(N <= a && a < 2 * N);
		return (a < S ? a + N : a) - S;
	}

	std::array<int, 2> get_node_bounds(point pt) const {
		int a = int(pt);
		assert(1 <= a && a < 2 * N);
		int l = __builtin_clz(a) - __builtin_clz(2*N-1);
		int x = a << l, y = (a+1) << l;
		assert(S <= x && x < y && y <= 2*S);
		return {(x >= 2 * N ? (x>>1) + N : x) - S, (y >= 2 * N ? (y>>1) + N : y) - S};
	}

	int get_node_split(point pt) const {
		int a = int(pt);
		assert(1 <= a && a < N);
		int l = __builtin_clz(2*a+1) - __builtin_clz(2*N-1);
		int x = (2*a+1) << l;
		assert(S <= x && x < 2*S);
		return (x >= 2 * N ? (x>>1) + N : x) - S;
	}

	int get_node_size(point pt) const {
		auto bounds = get_node_bounds(pt);
		return bounds[1] - bounds[0];
	}
};

struct circular_layout {
	// Alias them in for convenience
	using point = seg_tree::point;
	using range = seg_tree::range;

	int N;
	circular_layout() : N(0) {}
	circular_layout(int N_) : N(N_) {}

	point get_point(int a) const {
		assert(0 <= a && a < N);
		return point(N + a);
	}

	range get_range(int a, int b) const {
		assert(0 <= a && a <= b && b <= N);
		if (N == 0) return range();
		return range(N + a, N + b);
	}

	range get_range(std::array<int, 2> p) const {
		return get_range(p[0], p[1]);
	}

	int get_leaf_index(point pt) const {
		int a = int(pt);
		assert(N <= a && a < 2 * N);
		return a - N;
	}

	// Returns {x,y} so that 0 <= x < N and 1 <= y <= N
	// If the point is non-wrapping, then 0 <= x < y <= N
	std::array<int, 2> get_node_bounds(point pt) const {
		int a = int(pt);
		assert(1 <= a && a < 2 * N);
		int l = __builtin_clz(a) - __builtin_clz(2*N-1);
		int S = next_pow_2(N);
		int x = a << l, y = (a+1) << l;
		assert(S <= x && x < y && y <= 2*S);
		return {(x >= 2 * N ? x >> 1 : x) - N, (y > 2 * N ? y >> 1 : y) - N};
	}

	// Returns the split point of the node, such that 1 <= s <= N.
	int get_node_split(point pt) const {
		int a = int(pt);
		assert(1 <= a && a < N);
		return get_node_bounds(pt.c(0))[1];
	}

	int get_node_size(point pt) const {
		auto bounds = get_node_bounds(pt);
		int r = bounds[1] - bounds[0];
		return r > 0 ? r : r + N;
	}
};

} // namespace seg_tree

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int T;
	cin >> T;
	while (T--) {
		int N; cin >> N;
		std::vector<int> A(N);
		for (auto& a : A) cin >> a;
		std::vector<int64_t> pref(N+1);
		pref[0] = 0;
		for (int i = 0; i < N; i++) {
			pref[i+1] = pref[i] + A[i];
		}
		using num = modnum<998244353>;
		num ans = 0;
		
		seg_tree::in_order_layout layout(N+1);

		const int64_t INF = 1e18;

		struct seg_node {
			int64_t first_pref = -INF;
			int64_t first_substr = -INF;
			int64_t last_pref = -INF;
			int64_t last_substr = -INF;
			num sum_pref = -INF;
			num sum_substr = -INF;

			std::optional<int64_t> lazy_set_substr_from_pref;
			std::optional<int64_t> lazy_set_substr;
			std::optional<int64_t> lazy_set_pref;
		};

		std::vector<seg_node> seg(2*(N+1));

		auto apply_lazy_pref = [&](seg_tree::point a, int64_t v) {
			assert(v >= seg[a].first_pref);
			seg[a].first_pref = v;
			seg[a].last_pref = v;
			seg[a].sum_pref = layout.get_node_size(a) * v;
			seg[a].lazy_set_pref = v;
		};
		auto apply_lazy_substr = [&](seg_tree::point a, int64_t v) {
			seg[a].first_substr = v;
			seg[a].last_substr = v;
			seg[a].sum_substr = layout.get_node_size(a) * v;
			seg[a].lazy_set_substr_from_pref = std::nullopt;
			seg[a].lazy_set_substr = v;
		};
		auto apply_lazy_substr_from_pref = [&](seg_tree::point a, int64_t v) {
			if (seg[a].lazy_set_pref) {
				apply_lazy_substr(a, *seg[a].lazy_set_pref - v);
			}
			seg[a].first_substr = seg[a].first_pref - v;
			seg[a].last_substr = seg[a].last_pref - v;
			seg[a].sum_substr = seg[a].sum_pref - layout.get_node_size(a) * v;
			seg[a].lazy_set_substr = std::nullopt;
			seg[a].lazy_set_substr_from_pref = v;
		};

		auto downdate_node = [&](seg_tree::point a) {
			if (a >= layout.N) return;
			if (seg[a].lazy_set_substr_from_pref) {
				apply_lazy_substr_from_pref(a.c(0), *seg[a].lazy_set_substr_from_pref);
				apply_lazy_substr_from_pref(a.c(1), *seg[a].lazy_set_substr_from_pref);
				seg[a].lazy_set_substr_from_pref = std::nullopt;
			}
			if (seg[a].lazy_set_substr) {
				apply_lazy_substr(a.c(0), *seg[a].lazy_set_substr);
				apply_lazy_substr(a.c(1), *seg[a].lazy_set_substr);
				seg[a].lazy_set_substr = std::nullopt;
			}
			if (seg[a].lazy_set_pref) {
				apply_lazy_pref(a.c(0), *seg[a].lazy_set_pref);
				apply_lazy_pref(a.c(1), *seg[a].lazy_set_pref);
				seg[a].lazy_set_pref = std::nullopt;
			}
		};

		auto update_node = [&](seg_tree::point a) {
			assert(!seg[a].lazy_set_substr_from_pref);
			assert(!seg[a].lazy_set_substr);
			assert(!seg[a].lazy_set_pref);

			if (a >= layout.N) return;
			seg[a].first_pref = seg[a.c(0)].first_pref;
			seg[a].first_substr = seg[a.c(0)].first_substr;
			seg[a].last_pref = seg[a.c(1)].last_pref;
			seg[a].last_substr = seg[a.c(1)].last_substr;
			seg[a].sum_pref = seg[a.c(0)].sum_pref + seg[a.c(1)].sum_pref;
			seg[a].sum_substr = seg[a.c(0)].sum_substr + seg[a.c(1)].sum_substr;
		};
		for (int i = layout.N - 1; i > 0; i--) update_node(seg_tree::point(i));

		for (int l = N; l >= 0; l--) {
			auto rng = layout.get_range(l, N+1);
			rng.for_parents_down(downdate_node);
			auto set_max_prefs = std::y_combinator([&](auto self, seg_tree::point a) -> void {
				if (pref[l] > seg[a].last_pref) {
					apply_lazy_pref(a, pref[l]);
				} else if (pref[l] <= seg[a].first_pref) {
					return;
				} else {
					assert(a < layout.N);
					downdate_node(a);
					self(a.c(0));
					self(a.c(1));
					update_node(a);
				}
			});
			rng.for_each(set_max_prefs);

			auto set_substrs = std::y_combinator([&](auto self, seg_tree::point a) -> void {
				if (seg[a].last_pref - pref[l] > seg[a].last_substr) {
					apply_lazy_substr_from_pref(a, pref[l]);
				} else if (seg[a].first_pref - pref[l] <= seg[a].first_substr) {
					return;
				} else {
					assert(a < layout.N);
					downdate_node(a);
					self(a.c(0));
					self(a.c(1));
					update_node(a);
				}
			});
			rng.for_each(set_substrs);

			num tot_pref = 0;
			num tot_substr = 0;
			rng.for_each([&](seg_tree::point a) -> void {
				tot_pref += seg[a].sum_pref - layout.get_node_size(a) * pref[l];
				tot_substr += seg[a].sum_substr;
			});

			//cerr << l << ' ' << pref[l] << ' ' << tot_pref << ' ' << tot_substr << '\n';
			ans += tot_pref;
			ans += tot_substr;

			rng.for_parents_up(update_node);
		}

		cout << ans << '\n';
	}

	return 0;
}
