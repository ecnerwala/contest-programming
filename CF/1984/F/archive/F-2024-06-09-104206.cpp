template <typename T> T mod_inv_in_range(T a, T m) {
	// assert(0 <= a && a < m);
	T x = a, y = m;
	// coeff of a in x and y
	T vx = 1, vy = 0;
	while (x) {
		T k = y / x;
		y %= x;
		vy -= k * vx;
		std::swap(x, y);
		std::swap(vx, vy);
	}
	assert(y == 1);
	return vy < 0 ? m + vy : vy;
}

template <typename T> struct extended_gcd_result {
	T gcd;
	T coeff_a, coeff_b;
};
template <typename T> extended_gcd_result<T> extended_gcd(T a, T b) {
	T x = a, y = b;
	// coeff of a and b in x and y
	T ax = 1, ay = 0;
	T bx = 0, by = 1;
	while (x) {
		T k = y / x;
		y %= x;
		ay -= k * ax;
		by -= k * bx;
		std::swap(x, y);
		std::swap(ax, ay);
		std::swap(bx, by);
	}
	return {y, ay, by};
}

template <typename T> T mod_inv(T a, T m) {
	a %= m;
	a = a < 0 ? a + m : a;
	return mod_inv_in_range(a, m);
}

template <int MOD_> struct modnum {
	static constexpr int MOD = MOD_;
	static_assert(MOD_ > 0, "MOD must be positive");

private:
	int v;

public:

	modnum() : v(0) {}
	modnum(int64_t v_) : v(int(v_ % MOD)) { if (v < 0) v += MOD; }
	explicit operator int() const { return v; }
	friend std::ostream& operator << (std::ostream& out, const modnum& n) { return out << int(n); }
	friend std::istream& operator >> (std::istream& in, modnum& n) { int64_t v_; in >> v_; n = modnum(v_); return in; }

	friend bool operator == (const modnum& a, const modnum& b) { return a.v == b.v; }
	friend bool operator != (const modnum& a, const modnum& b) { return a.v != b.v; }

	modnum inv() const {
		modnum res;
		res.v = mod_inv_in_range(v, MOD);
		return res;
	}
	friend modnum inv(const modnum& m) { return m.inv(); }
	modnum neg() const {
		modnum res;
		res.v = v ? MOD-v : 0;
		return res;
	}
	friend modnum neg(const modnum& m) { return m.neg(); }

	modnum operator- () const {
		return neg();
	}
	modnum operator+ () const {
		return modnum(*this);
	}

	modnum& operator ++ () {
		v ++;
		if (v == MOD) v = 0;
		return *this;
	}
	modnum& operator -- () {
		if (v == 0) v = MOD;
		v --;
		return *this;
	}
	modnum& operator += (const modnum& o) {
		v -= MOD-o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator -= (const modnum& o) {
		v -= o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator *= (const modnum& o) {
		v = int(int64_t(v) * int64_t(o.v) % MOD);
		return *this;
	}
	modnum& operator /= (const modnum& o) {
		return *this *= o.inv();
	}

	friend modnum operator ++ (modnum& a, int) { modnum r = a; ++a; return r; }
	friend modnum operator -- (modnum& a, int) { modnum r = a; --a; return r; }
	friend modnum operator + (const modnum& a, const modnum& b) { return modnum(a) += b; }
	friend modnum operator - (const modnum& a, const modnum& b) { return modnum(a) -= b; }
	friend modnum operator * (const modnum& a, const modnum& b) { return modnum(a) *= b; }
	friend modnum operator / (const modnum& a, const modnum& b) { return modnum(a) /= b; }
};

template <typename T> T pow(T a, long long b) {
	assert(b >= 0);
	T r = 1; while (b) { if (b & 1) r *= a; b >>= 1; a *= a; } return r;
}

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int T; cin >> T;
	while (T--) {
		int N; int64_t M; cin >> N >> M;
		std::string S; cin >> S;
		assert(int(S.size()) == N);
		std::vector<int64_t> B(N);
		for (auto& a : B) cin >> a;

		// implicit ones
		S.insert(S.begin(), 'P');
		B.insert(B.begin(), 0);

		S.insert(S.end(), 'S');
		B.insert(B.end(), 0);

		using num = modnum<998244353>;
		std::vector<std::pair<int64_t, int>> sums(N+1);
		for (int i = 0; i <= N; i++) {
			sums[i] = {B[i] + B[i+1], i};
		}
		std::sort(sums.begin(), sums.end());
		using mat_t = std::array<std::array<num, 2>, 2>;
		seg_tree::in_order_layout layout(2*N+1);
		std::vector<mat_t> seg(2 * layout.N);
		auto update_node = [&](seg_tree::point a) -> void {
			int l = a.c(0);
			int r = a.c(1);
			for (int i = 0; i < 2; i++) {
				for (int j = 0; j < 2; j++) {
					seg[a][i][j] = seg[l][i][0] * seg[r][0][j] + seg[l][i][1] * seg[r][1][j];
				}
			}
		};
		for (int i = 0; i < 2*N+1; i++) {
			auto a = layout.get_point(i);
			if (i % 2 == 0) {
				seg[a][0][0] = seg[a][1][1] = std::abs(B[i/2+1] - B[i/2]) <= M;
				seg[a][0][1] = seg[a][1][0] = false;
			} else {
				seg[a][0][1] = seg[a][1][0] = false;
				char c = S[(i+1)/2];
				cerr << c << '\n';
				seg[a][0][0] = (c == 'P' || c == '?');
				seg[a][1][1] = (c == 'S' || c == '?');
			}
		}
		for (seg_tree::point a(layout.N-1); a > 0; a--) update_node(a);

		num ans = 0;
		int lo = 0;
		int hi = 0;
		for (int i = 0, j = 0; i < int(sums.size()); i = j) {
			int64_t s = sums[i].first;
			for (; j < int(sums.size()) && sums[j].first == s; j++) { }
			for (int k = i; k < j; k++) {
				seg_tree::point a = layout.get_point(2*k);
				seg[a][0][1] = 1;
				a.for_parents_up(update_node);
			}
			for (; hi < int(sums.size()) && sums[hi].first <= s + 2 * M; hi++) {
				seg_tree::point a = layout.get_point(2*sums[hi].second);
				assert(seg[a][1][0] == 0);
				seg[a][1][0] = 1;
				a.for_parents_up(update_node);
			}
			for (; lo < int(sums.size()) && sums[lo].first < s - 2 * M; lo++) {
				assert(lo < hi);
				seg_tree::point a = layout.get_point(2*sums[lo].second);
				assert(seg[a][1][0] == 1);
				seg[a][1][0] = 0;
				a.for_parents_up(update_node);
			}
			ans += seg[1][0][1];
			for (int k = i; k < j; k++) {
				seg_tree::point a = layout.get_point(k);
				seg[a][0][1] = 0;
				a.for_parents_up(update_node);
			}
		}
		cout << ans << '\n';
	}

	return 0;
}
