int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);
	array<int, 2> N; int Q; cin >> N[0] >> N[1] >> Q;
	array<vector<pair<int, int>>, 2> A;
	for (int z = 0; z < 2; z++) {
		A[z].resize(N[z]+2);
		for (int i = 1; i <= N[z]; i++) {
			cin >> A[z][i].first; A[z][i].second = i;
		}
	}
	vector<int> queries(Q); for (auto& q : queries) cin >> q;

	const int X = int(1e5) + 100;
	vector<long long> ans(2 * X - 1);

	for (int round = 0; round < 2; round++) {
		const int INF = 1e9;
		array<vector<double>, 2> mults;
		for (int z = 0; z < 2; z++) {
			mults[z].assign(X, 0);

			A[z][0].first = A[z][N[z]+1].first = round ? INF : -INF;
			for (int i = 1; i <= N[z]; i++) {
				if (A[z][i] < A[z][i-1] && A[z][i] < A[z][i+1]) {
					mults[z][A[z][i].first]--;
				} else if (A[z][i] > A[z][i-1] && A[z][i] > A[z][i+1]) {
					mults[z][A[z][i].first]++;
				}
			}
		}
		vector<double> cur_res = fft::multiply(mults[0], mults[1]);
		for (int i = 0; i < 2 * X - 1; i++) {
			long long v = ((cur_res[i] > 0) - (cur_res[i] < 0)) * (long long)(abs(cur_res[i]) + 0.5);
			ans[i] += v;
		}
	}
	for (int i = 2 * X - 3; i >= 0; i--) {
		ans[i] += ans[i+1];
	}
	long long tot = ans[0];
	for (auto& a : ans) a = (2 * a - tot) / 2;
	for (int q : queries) {
		cout << ans[q] << '\n';
	}

	return 0;
}

