class UpdownNumbers {

public:

	std::vector<int> precompute(int S, int maxD) {
		using num = modnum<int(1e9)+7>;
		using state_t = std::pair<std::array<int, 10>, std::array<int, 10>>;
		std::map<state_t, num> dp;
		std::pair<std::array<int, 10>, std::array<int, 10>> start;
		start.first.fill(10);
		start.second.fill(-1);
		std::pair<std::array<int, 10>, std::array<int, 10>> end;
		end.first.fill(-1);
		end.second.fill(10);

		dp[start] = num(1);
		std::vector<int> res(maxD+1);
		res[0] = int(dp[end]);
		for (int l = 0; l < maxD; l++) {
			cerr << S << ' ' << l << ' ' << dp.size() << '\n';
			std::map<state_t, num> ndp;
			for (auto it : dp) {
				for (int d = (l == 0) ? 1 : 0; d < 10; d++) {
					auto state = it.first;
					if (state.first[S-1] == 10) {
						int i = 0;
						while (i < int(state.first.size()) && d > state.first[i]) i++;
						if (i == S-1) {
							state.first.fill(-1);
						} else {
							state.first[i] = d;
						}
					}
					if (state.second[S-1] == -1) {
						int i = 0;
						while (i < int(state.second.size()) && d < state.second[i]) i++;
						if (i == S-1) {
							state.second.fill(10);
						} else {
							state.second[i] = d;
						}
					}
					ndp[state] += it.second;
				}
			}
			dp = ndp;
			res[l+1] = int(dp[end]);
		}
		return res;
	}

	int count(int D, int S) {
		return answers[S][D];
	}
};

