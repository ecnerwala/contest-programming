template <typename T> T mod_inv_in_range(T a, T m) {
	// assert(0 <= a && a < m);
	T x = a, y = m;
	// coeff of a in x and y
	T vx = 1, vy = 0;
	while (x) {
		T k = y / x;
		y %= x;
		vy -= k * vx;
		std::swap(x, y);
		std::swap(vx, vy);
	}
	assert(y == 1);
	return vy < 0 ? m + vy : vy;
}

template <typename T> struct extended_gcd_result {
	T gcd;
	T coeff_a, coeff_b;
};
template <typename T> extended_gcd_result<T> extended_gcd(T a, T b) {
	T x = a, y = b;
	// coeff of a and b in x and y
	T ax = 1, ay = 0;
	T bx = 0, by = 1;
	while (x) {
		T k = y / x;
		y %= x;
		ay -= k * ax;
		by -= k * bx;
		std::swap(x, y);
		std::swap(ax, ay);
		std::swap(bx, by);
	}
	return {y, ay, by};
}

template <typename T> T mod_inv(T a, T m) {
	a %= m;
	a = a < 0 ? a + m : a;
	return mod_inv_in_range(a, m);
}

template <int MOD_> struct modnum {
	static constexpr int MOD = MOD_;
	static_assert(MOD_ > 0, "MOD must be positive");

private:
	int v;

public:

	modnum() : v(0) {}
	modnum(int64_t v_) : v(int(v_ % MOD)) { if (v < 0) v += MOD; }
	explicit operator int() const { return v; }
	friend std::ostream& operator << (std::ostream& out, const modnum& n) { return out << int(n); }
	friend std::istream& operator >> (std::istream& in, modnum& n) { int64_t v_; in >> v_; n = modnum(v_); return in; }

	friend bool operator == (const modnum& a, const modnum& b) { return a.v == b.v; }
	friend bool operator != (const modnum& a, const modnum& b) { return a.v != b.v; }

	modnum inv() const {
		modnum res;
		res.v = mod_inv_in_range(v, MOD);
		return res;
	}
	friend modnum inv(const modnum& m) { return m.inv(); }
	modnum neg() const {
		modnum res;
		res.v = v ? MOD-v : 0;
		return res;
	}
	friend modnum neg(const modnum& m) { return m.neg(); }

	modnum operator- () const {
		return neg();
	}
	modnum operator+ () const {
		return modnum(*this);
	}

	modnum& operator ++ () {
		v ++;
		if (v == MOD) v = 0;
		return *this;
	}
	modnum& operator -- () {
		if (v == 0) v = MOD;
		v --;
		return *this;
	}
	modnum& operator += (const modnum& o) {
		v -= MOD-o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator -= (const modnum& o) {
		v -= o.v;
		v = (v < 0) ? v + MOD : v;
		return *this;
	}
	modnum& operator *= (const modnum& o) {
		v = int(int64_t(v) * int64_t(o.v) % MOD);
		return *this;
	}
	modnum& operator /= (const modnum& o) {
		return *this *= o.inv();
	}

	friend modnum operator ++ (modnum& a, int) { modnum r = a; ++a; return r; }
	friend modnum operator -- (modnum& a, int) { modnum r = a; --a; return r; }
	friend modnum operator + (const modnum& a, const modnum& b) { return modnum(a) += b; }
	friend modnum operator - (const modnum& a, const modnum& b) { return modnum(a) -= b; }
	friend modnum operator * (const modnum& a, const modnum& b) { return modnum(a) *= b; }
	friend modnum operator / (const modnum& a, const modnum& b) { return modnum(a) /= b; }
};

int main() {
	using namespace std;
	ios_base::sync_with_stdio(false), cin.tie(nullptr);

	int N, K; cin >> N >> K;
	std::vector<int> P(N);
	for (int i = 0; i < N; i++) {
		cin >> P[i]; P[i]--;
	}

	std::vector<int> loc(N);
	for (int i = 0; i < N; i++) {
		loc[P[i]] = i;
	}

	using mnum = modnum<998244353>;
	mnum ans = 1;

	const int INF = 3*(N+K);
	const int S = N+2;
	std::vector<int> left_val(S);
	std::vector<int> nxt_left(S);
	std::vector<int> prv_left(S);
	std::vector<int> right_val(S);
	std::vector<int> nxt_right(S);
	std::vector<int> prv_right(S);

	std::set<std::pair<int, int>> bads;
	order_statistic_set<int> alive_lefts;

	for (int i = 0; i <= N+1; i++) {
		prv_left[i] = i-1;
		nxt_left[i] = i+1;
		prv_right[i] = i-1;
		nxt_right[i] = i+1;
		left_val[i] = (i == 0) ? INF : i-2;
		right_val[i] = (i == S-1) ? -INF : i;
	}
	for (int i = 0; i <= N; i++) {
		alive_lefts.insert(i);
		if (right_val[i+1] - left_val[i] <= K) {
			bads.insert(std::pair<int, int>{i, i+1});
		}
	}

	order_statistic_set<int> alive_inds;
	for (int i = 0; i < N; i++) {
		alive_inds.insert(i);
	}

	std::vector<std::pair<int, int>> buf; buf.reserve(4);
	for (int v = 0; v < N; v++) {
		/*
		cerr << "left ll" << '\n';
		for (int i = 0; i < S; i++) {
			if (nxt_left[i] == i) continue;
			cerr << prv_left[i] << '-' << i << '-' << nxt_left[i] << ' ' << left_val[i] << '\n';
		}
		cerr << "right ll" << '\n';
		for (int i = 0; i < S; i++) {
			if (nxt_right[i] == i) continue;
			cerr << prv_right[i] << '-' << i << '-' << nxt_right[i] << ' ' << right_val[i] << '\n';
		}
		cerr << "bads" << '\n';
		for (auto [l, r] : bads) {
			cerr << l << ' ' << r << ' ' << left_val[l] << ' ' << right_val[r] << '\n';
		}
		cerr << "alive_lefts" << '\n';
		for (int i : alive_lefts) {
			cerr << i << ' ' << left_val[i] << '\n';
		}
		cerr << '\n';
		*/

		int orig_idx = loc[v];
		int num_smaller = int(alive_inds.order_of_key(orig_idx));
		alive_inds.erase(orig_idx);

		int left_lo = *alive_lefts.find_by_order(num_smaller);

		auto it_hi = bads.lower_bound({left_lo + 1, -1});
		auto it_lo = std::prev(it_hi);

		int idx_hi = int(alive_lefts.order_of_key(it_hi->first));
		int idx_lo = int(alive_lefts.order_of_key(it_lo->first));
		assert(idx_lo <= num_smaller && num_smaller+1 <= idx_hi);

		//cerr << "ans " << idx_hi - idx_lo << '\n' << '\n';
		ans *= mnum(idx_hi - idx_lo);

		int r_erase = prv_right[it_lo->second];
		int l_erase = nxt_left[it_hi->first];

		buf.clear();
		if (it_lo != bads.begin() && std::prev(it_lo)->second == r_erase) {
			buf.push_back(*std::prev(it_lo));
			bads.erase(std::prev(it_lo));
		}
		buf.push_back(*it_lo);
		buf.push_back(*it_hi);
		if (std::next(it_hi) != bads.end() && std::next(it_hi)->first == l_erase) {
			buf.push_back(*std::next(it_hi));
			bads.erase(std::next(it_hi));
		}

		bads.erase(it_lo);
		bads.erase(it_hi);

		alive_lefts.erase(l_erase);

		for (int z = 0; z+1 < int(buf.size()); z++) {
			auto [al, ar] = buf[z];
			auto [bl, br] = buf[z+1];
			if (nxt_left[al] == bl) {
				assert(nxt_right[ar] == br);
				if (right_val[br] - left_val[al] <= K) {
					bads.insert({al, br});
				}
			}
			if (al == 0) {
				bads.insert({al, nxt_right[ar]});
			}
			if (br == S-1) {
				bads.insert({prv_left[bl], br});
			}
		}

		// erase r_erase and l_erase from the linked list and insert the new potentially bad things
		{
			int p = prv_right[r_erase];
			int n = nxt_right[r_erase];
			prv_right[r_erase] = nxt_right[r_erase] = r_erase;
			assert(n != S);
			prv_right[n] = p;
			if (p != -1) nxt_right[p] = n;
			r_erase = n;
		}
		{
			int p = prv_left[l_erase];
			int n = nxt_left[l_erase];
			prv_left[l_erase] = nxt_left[l_erase] = l_erase;
			assert(p != -1);
			nxt_left[p] = n;
			if (n != S) prv_left[n] = p;
			l_erase = p;
		}
	}
	cout << ans << '\n';

	return 0;
}
